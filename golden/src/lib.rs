//! Bit-exact golden models for the NPX-001 Scope A RTL.
//! Every function here defines the contract the SystemVerilog must meet.
#![forbid(unsafe_code)]

/// xorshift64* PRNG: deterministic, dependency-free, used only for test vectors.
pub struct Rng(pub u64);
impl Rng {
    pub fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545F4914F6CDD1D)
    }
    pub fn below(&mut self, n: u64) -> u64 { self.next() % n }
    pub fn chance(&mut self, pct: u64) -> bool { self.below(100) < pct }
}

// ---------------------------------------------------------------- exp2 LUT
pub mod lut {
    /// LUT[f] = round(32768 * 2^(f/256)), f in 0..256. Single source of truth:
    /// the RTL include file is generated from this function.
    pub fn exp2_q15() -> [u16; 256] {
        let mut t = [0u16; 256];
        for (f, e) in t.iter_mut().enumerate() {
            *e = (32768.0 * (2f64).powf(f as f64 / 256.0)).round() as u32 as u16;
        }
        t
    }
    pub fn to_svh() -> String {
        let t = exp2_q15();
        let mut s = String::from("// GENERATED by npx-golden gen_vectors. Do not edit.\n// exp2 LUT, Q15: LUT[f] = round(32768 * 2^(f/256))\n");
        s.push_str("function automatic logic [15:0] exp2_lut(input logic [7:0] f);\n  case (f)\n");
        for (i, v) in t.iter().enumerate() {
            s.push_str(&format!("    8'd{i}: exp2_lut = 16'd{v};\n"));
        }
        s.push_str("    default: exp2_lut = 16'd0;\n  endcase\nendfunction\n");
        s
    }
}

// ------------------------------------------------------------ softmax island
pub mod softmax {
    pub const N: usize = 8;
    /// Fixed-point softmax. Input: Q8.8 scores (i16). Output: Q15 probabilities (u16).
    /// d = s - max; u = (d*369)>>8 (log2(e) ~ 369/256, floor); 2^u = LUT[u&255] >> (-(u>>8)).
    pub fn q15(s: &[i16; N]) -> [u16; N] {
        let lut = super::lut::exp2_q15();
        let mx = *s.iter().max().unwrap() as i32;
        let mut e = [0u32; N];
        let mut sum = 0u32;
        for i in 0..N {
            let d = s[i] as i32 - mx;
            let u = (d * 369) >> 8;
            let k = u >> 8;
            let f = (u & 0xFF) as usize;
            let sh = -k;
            e[i] = if sh >= 16 { 0 } else { (lut[f] as u32) >> sh };
            sum += e[i];
        }
        let mut p = [0u16; N];
        for i in 0..N { p[i] = (((e[i] as u64) << 15) / sum as u64) as u16; }
        p
    }
}

// ---------------------------------------------------------- digital CiM tile
pub mod cim {
    pub const ROWS: usize = 16;
    pub const COLS: usize = 8;
    /// y[c] = sum_r w[r][c] * x[r], INT8 x INT8 -> INT32. w is row-major [ROWS][COLS].
    pub fn dot(w: &[i8], x: &[i8]) -> [i32; COLS] {
        let mut y = [0i32; COLS];
        for c in 0..COLS { for r in 0..ROWS { y[c] += w[r * COLS + c] as i32 * x[r] as i32; } }
        y
    }
    /// Bit-serial model matching the RTL datapath (MSB plane subtracts).
    pub fn bit_serial(w: &[i8], x: &[i8]) -> [i32; COLS] {
        let mut acc = [0i32; COLS];
        for b in 0..8u32 {
            for c in 0..COLS {
                let mut part = 0i32;
                for r in 0..ROWS { if (x[r] as u8 >> b) & 1 == 1 { part += w[r * COLS + c] as i32; } }
                acc[c] += if b == 7 { -(part << 7) } else { part << b };
            }
        }
        acc
    }
}

// -------------------------------------------------------- KV page allocator
pub mod alloc {
    pub const NSEQ: usize = 16;
    pub const MAXLP: usize = 16;
    pub const NPAGES: usize = 64;
    pub const OK: u8 = 0; pub const NOSEQ: u8 = 1; pub const TENANT: u8 = 2;
    pub const FULLSEQ: u8 = 3; pub const NOMEM: u8 = 4; pub const RANGE: u8 = 5; pub const EXISTS: u8 = 6;
    pub const OP_OPEN: u8 = 0; pub const OP_ALLOC: u8 = 1; pub const OP_LOOKUP: u8 = 2; pub const OP_FREE: u8 = 3;

    pub struct Alloc {
        open: [bool; NSEQ], tenant: [u8; NSEQ], len: [usize; NSEQ],
        pt: [[u8; MAXLP]; NSEQ], free: u64,
    }
    impl Alloc {
        pub fn new() -> Self {
            Self { open: [false; NSEQ], tenant: [0; NSEQ], len: [0; NSEQ], pt: [[0; MAXLP]; NSEQ], free: u64::MAX }
        }
        pub fn free_count(&self) -> u32 { self.free.count_ones() }
        /// Returns (status, val). val = page id (ALLOC/LOOKUP), pages freed (FREE), else 0.
        pub fn step(&mut self, op: u8, seq: usize, tenant: u8, lp: usize) -> (u8, u8) {
            match op {
                OP_OPEN => {
                    if self.open[seq] { return (EXISTS, 0); }
                    self.open[seq] = true; self.tenant[seq] = tenant; self.len[seq] = 0; (OK, 0)
                }
                OP_ALLOC => {
                    if !self.open[seq] { return (NOSEQ, 0); }
                    if self.tenant[seq] != tenant { return (TENANT, 0); }
                    if self.len[seq] == MAXLP { return (FULLSEQ, 0); }
                    if self.free == 0 { return (NOMEM, 0); }
                    let p = self.free.trailing_zeros() as u8;
                    self.free &= !(1u64 << p);
                    self.pt[seq][self.len[seq]] = p; self.len[seq] += 1; (OK, p)
                }
                OP_LOOKUP => {
                    if !self.open[seq] { return (NOSEQ, 0); }
                    if self.tenant[seq] != tenant { return (TENANT, 0); }
                    if lp >= self.len[seq] { return (RANGE, 0); }
                    (OK, self.pt[seq][lp])
                }
                OP_FREE => {
                    if !self.open[seq] { return (NOSEQ, 0); }
                    if self.tenant[seq] != tenant { return (TENANT, 0); }
                    let n = self.len[seq];
                    for i in 0..n { self.free |= 1u64 << self.pt[seq][i]; }
                    self.open[seq] = false; self.len[seq] = 0; (OK, n as u8)
                }
                _ => unreachable!(),
            }
        }
    }
}

// ------------------------------------------------------- command descriptor
pub mod decode {
    //! 128-bit command descriptor (report Section 6.2), Scope A field layout.
    pub const E_RESERVED: u8 = 1; pub const E_RESOURCE: u8 = 2; pub const E_PRECISION: u8 = 3;
    pub const E_DIM: u8 = 4; pub const E_ALIGN: u8 = 5; pub const E_KV: u8 = 6; pub const E_TENANT: u8 = 7;
    /// Returns (status, dispatch one-hot: bit0 CiM, bit1 photonic, bit2 digital). dispatch=0 unless status==0.
    pub fn decode(d: u128, photonic_en: bool, kv_open: u16, kv_tenants: u64) -> (u8, u8) {
        let res = ((d >> 8) & 3) as u8;
        let prec = ((d >> 10) & 0xF) as u8;
        let tenant = ((d >> 14) & 0xF) as u8;
        let kvseq = ((d >> 18) & 0xF) as usize;
        let kvvalid = (d >> 22) & 1 == 1;
        let rsv1 = (d >> 24) & 0xFF;
        let addr = ((d >> 32) & 0xFFFF_FFFF) as u32;
        let m = ((d >> 64) & 0xFFFF) as u16;
        let n = ((d >> 80) & 0xFFFF) as u16;
        let rsv2 = (d >> 116) & 0xFFF;
        if rsv1 != 0 || rsv2 != 0 { return (E_RESERVED, 0); }
        if res == 3 || (res == 1 && !photonic_en) { return (E_RESOURCE, 0); }
        let ok_prec = match res { 0 => matches!(prec, 0 | 1 | 3), 1 => matches!(prec, 0 | 2), _ => matches!(prec, 0 | 2 | 3) };
        if !ok_prec { return (E_PRECISION, 0); }
        if m == 0 || n == 0 { return (E_DIM, 0); }
        if addr & 0x1F != 0 { return (E_ALIGN, 0); }
        if kvvalid {
            if (kv_open >> kvseq) & 1 == 0 { return (E_KV, 0); }
            if ((kv_tenants >> (kvseq * 4)) & 0xF) as u8 != tenant { return (E_TENANT, 0); }
        }
        (0, 1 << res)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lut_range_and_monotone() {
        let t = lut::exp2_q15();
        assert_eq!(t[0], 32768);
        assert!(t.windows(2).all(|w| w[0] < w[1]));
        assert!((t[255] as u32) < 65536 - 100);
    }

    #[test]
    fn softmax_close_to_float() {
        let mut r = Rng(0x1234_5678_9abc_def1);
        for _ in 0..2000 {
            let mut s = [0i16; softmax::N];
            for v in s.iter_mut() { *v = (r.below(4096) as i64 - 2048) as i16; }
            let p = softmax::q15(&s);
            let mx = *s.iter().max().unwrap() as f64 / 256.0;
            let ex: Vec<f64> = s.iter().map(|&v| (v as f64 / 256.0 - mx).exp()).collect();
            let z: f64 = ex.iter().sum();
            for i in 0..softmax::N {
                let want = ex[i] / z * 32768.0;
                // log2(e) truncation (369/256 vs 1.4427) dominates; bound is empirical and stated, not proved
                assert!((p[i] as f64 - want).abs() < 600.0, "i={i} got={} want={want}", p[i]);
            }
            let tot: u32 = p.iter().map(|&v| v as u32).sum();
            assert!(tot <= 32768 && tot >= 32768 - softmax::N as u32);
        }
    }

    #[test]
    fn cim_bit_serial_equals_dot() {
        let mut r = Rng(42);
        for _ in 0..2000 {
            let w: Vec<i8> = (0..cim::ROWS * cim::COLS).map(|_| r.next() as i8).collect();
            let x: Vec<i8> = (0..cim::ROWS).map(|_| r.next() as i8).collect();
            assert_eq!(cim::dot(&w, &x), cim::bit_serial(&w, &x));
        }
        // extremes
        let w = vec![-128i8; cim::ROWS * cim::COLS];
        let x = vec![-128i8; cim::ROWS];
        assert_eq!(cim::dot(&w, &x), cim::bit_serial(&w, &x));
    }

    #[test]
    fn alloc_isolation_and_conservation() {
        let mut a = alloc::Alloc::new();
        assert_eq!(a.step(alloc::OP_OPEN, 0, 1, 0), (alloc::OK, 0));
        assert_eq!(a.step(alloc::OP_ALLOC, 0, 2, 0).0, alloc::TENANT); // cross-tenant refused
        let (s, p) = a.step(alloc::OP_ALLOC, 0, 1, 0);
        assert_eq!(s, alloc::OK);
        assert_eq!(a.step(alloc::OP_LOOKUP, 0, 3, 0).0, alloc::TENANT);
        assert_eq!(a.step(alloc::OP_LOOKUP, 0, 1, 0), (alloc::OK, p));
        assert_eq!(a.free_count(), 63);
        assert_eq!(a.step(alloc::OP_FREE, 0, 1, 0), (alloc::OK, 1));
        assert_eq!(a.free_count(), 64);
    }

    #[test]
    fn decode_basic() {
        // CiM, INT8, tenant 3, no kv, addr 0x100, 4x4
        let d: u128 = (0 << 8) | (0 << 10) | (3 << 14) | (0x100u128 << 32) | (4u128 << 64) | (4u128 << 80);
        assert_eq!(decode::decode(d, false, 0, 0), (0, 1));
        let ph = d | (1 << 8);
        assert_eq!(decode::decode(ph, false, 0, 0).0, decode::E_RESOURCE);
        assert_eq!(decode::decode(ph, true, 0, 0), (0, 2));
    }
}
